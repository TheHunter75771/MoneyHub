"""One-way Notion projection.

Notion is NEVER a source of truth — it receives a read-only snapshot so
phone/chat workflows can see balances and budget without touching the
database. Each push creates a dated child page under NOTION_PARENT_PAGE_ID.

Configuration (gitignored .env):
    NOTION_TOKEN=secret_…            an internal-integration token
    NOTION_PARENT_PAGE_ID=…          page shared with that integration

Push state (last attempt/result) is kept in data/notion-state.json — local
operational state, not ledger data.
"""
from __future__ import annotations

import json
import urllib.request
from datetime import UTC, date, datetime
from pathlib import Path

from sqlalchemy import select
from sqlalchemy.orm import Session

from .models import Account, BalanceSnapshot, Debt
from .money import from_cents
from .reports import budget_report
from .simplefin import load_env

NOTION_API = "https://api.notion.com/v1/pages"
NOTION_VERSION = "2022-06-28"
STATE_PATH = Path("data/notion-state.json")


class NotionError(RuntimeError):
    pass


def config() -> dict[str, str]:
    env = load_env()
    return {
        "token": env.get("NOTION_TOKEN", ""),
        "parent": env.get("NOTION_PARENT_PAGE_ID", ""),
    }


def status() -> dict:
    cfg = config()
    state = {}
    if STATE_PATH.exists():
        try:
            state = json.loads(STATE_PATH.read_text())
        except ValueError:
            state = {}
    return {
        "configured": bool(cfg["token"] and cfg["parent"]),
        "last_push_at": state.get("last_push_at"),
        "last_result": state.get("last_result"),
        "last_page_url": state.get("last_page_url"),
    }


def _save_state(result: str, page_url: str | None = None) -> None:
    STATE_PATH.parent.mkdir(exist_ok=True)
    STATE_PATH.write_text(
        json.dumps(
            {
                "last_push_at": datetime.now(tz=UTC).isoformat(),
                "last_result": result,
                "last_page_url": page_url,
            }
        )
    )


def _paragraph(text: str) -> dict:
    return {
        "object": "block",
        "type": "paragraph",
        "paragraph": {"rich_text": [{"type": "text", "text": {"content": text[:2000]}}]},
    }


def _heading(text: str) -> dict:
    return {
        "object": "block",
        "type": "heading_2",
        "heading_2": {"rich_text": [{"type": "text", "text": {"content": text}}]},
    }


def build_snapshot_blocks(session: Session) -> list[dict]:
    today = date.today()
    blocks: list[dict] = []

    blocks.append(_heading("Balances"))
    snaps: dict[int, BalanceSnapshot] = {}
    for snap in session.scalars(select(BalanceSnapshot).order_by(BalanceSnapshot.as_of)):
        snaps[snap.account_id] = snap
    for account in session.scalars(
        select(Account).where(Account.is_active.is_(True)).order_by(Account.name)
    ):
        snap = snaps.get(account.id)
        if snap is None:
            continue
        blocks.append(
            _paragraph(f"{account.name}: ${from_cents(snap.balance_cents)} (as of {snap.as_of})")
        )

    blocks.append(_heading(f"Budget — {today.strftime('%B %Y')}"))
    report = budget_report(session, today.year, today.month)
    blocks.append(
        _paragraph(
            f"Income ${from_cents(report.income_cents)} · "
            f"Spending ${from_cents(report.spending_cents)}"
        )
    )
    for line in sorted(report.lines, key=lambda x: -x.spent_cents):
        if line.grp in ("transfer", "income") or line.spent_cents == 0:
            continue
        cap = f" / ${from_cents(line.budget_cents)}" if line.budget_cents is not None else ""
        over = " — OVER" if line.remaining_cents is not None and line.remaining_cents < 0 else ""
        blocks.append(_paragraph(f"{line.category}: ${from_cents(line.spent_cents)}{cap}{over}"))

    blocks.append(_heading("Debts"))
    total = 0
    for debt in session.scalars(select(Debt).where(Debt.status == "open")):
        total += debt.balance_cents
        blocks.append(_paragraph(f"{debt.name}: ${from_cents(debt.balance_cents)}"))
    blocks.append(_paragraph(f"Total owed: ${from_cents(total)}"))
    blocks.append(_paragraph("Generated by Money Hub — read-only projection, never edit here."))
    return blocks


def push_snapshot(session: Session) -> dict:
    cfg = config()
    if not (cfg["token"] and cfg["parent"]):
        raise NotionError(
            "Notion is not configured — set NOTION_TOKEN and NOTION_PARENT_PAGE_ID in .env"
        )
    payload = {
        "parent": {"page_id": cfg["parent"]},
        "properties": {
            "title": [
                {
                    "type": "text",
                    "text": {"content": f"Money Hub — {date.today().isoformat()}"},
                }
            ]
        },
        "children": build_snapshot_blocks(session)[:100],  # Notion caps children per call
    }
    request = urllib.request.Request(
        NOTION_API,
        data=json.dumps(payload).encode(),
        method="POST",
        headers={
            "Authorization": f"Bearer {cfg['token']}",
            "Notion-Version": NOTION_VERSION,
            "Content-Type": "application/json",
            "User-Agent": "moneyhub/0.1",
        },
    )
    try:
        with urllib.request.urlopen(request, timeout=30) as response:
            body = json.loads(response.read())
    except urllib.error.HTTPError as exc:
        detail = exc.read().decode(errors="replace")[:300]
        _save_state(f"failed: HTTP {exc.code}")
        raise NotionError(f"Notion push failed: HTTP {exc.code} — {detail}") from exc
    url = body.get("url")
    _save_state("ok", url)
    return {"ok": True, "page_url": url}
